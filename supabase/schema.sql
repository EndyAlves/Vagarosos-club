create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$$;

-- Cadastro: valida a chave de membro e o username ANTES de criar o usuário
create or replace function private.before_new_user()
returns trigger language plpgsql security definer set search_path = public, private as $$
declare
  k text;
  u text := lower(coalesce(new.raw_user_meta_data ->> 'username', ''));
begin
  select value into k from private.settings where key = 'invite_key';
  if coalesce(new.raw_user_meta_data ->> 'invite_key', '') is distinct from k then
    raise exception 'invalid_invite_key';
  end if;
  if u !~ '^[a-z0-9._]{3,20}$' then raise exception 'invalid_username'; end if;
  if exists (select 1 from public.profiles where username = u) then raise exception 'username_taken'; end if;
  -- não guarda a chave junto do usuário
  new.raw_user_meta_data := (new.raw_user_meta_data - 'invite_key') || jsonb_build_object('username', u);
  return new;
end $$;

create or replace function private.after_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username) values (new.id, new.raw_user_meta_data ->> 'username');
  return new;
end $$;

drop trigger if exists vagarosos_before_new_user on auth.users;
create trigger vagarosos_before_new_user before insert on auth.users
  for each row execute function private.before_new_user();
drop trigger if exists vagarosos_after_new_user on auth.users;
create trigger vagarosos_after_new_user after insert on auth.users
  for each row execute function private.after_new_user();

-- Verificação amigável antes do cadastro (o gatilho acima garante de qualquer forma)
create or replace function public.check_signup(p_username text, p_key text)
returns text language plpgsql security definer set search_path = public, private as $$
begin
  if lower(coalesce(p_username, '')) !~ '^[a-z0-9._]{3,20}$' then return 'bad_username'; end if;
  if exists (select 1 from public.profiles where username = lower(p_username)) then return 'taken'; end if;
  if p_key is distinct from (select value from private.settings where key = 'invite_key') then
    perform pg_sleep(0.6);   -- atrasa tentativas de adivinhar a chave
    return 'bad_key';
  end if;
  return 'ok';
end $$;

-- Admin: ver e trocar a chave de membro
create or replace function public.get_invite_key()
returns text language plpgsql security definer set search_path = public, private as $$
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  return (select value from private.settings where key = 'invite_key');
end $$;

create or replace function public.set_invite_key(p_key text)
returns void language plpgsql security definer set search_path = public, private as $$
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  if char_length(trim(coalesce(p_key, ''))) < 6 then raise exception 'key_too_short'; end if;
  update private.settings set value = trim(p_key) where key = 'invite_key';
end $$;

-- Treino: soma XP no servidor (o usuário não consegue editar o próprio XP)
create or replace function public.train_tick(p_jorney bigint)
returns json language plpgsql security definer set search_path = public as $$
declare
  j          public.jorneys;
  p          public.profiles;
  gain       int;
  old_level  int;
  daily_cap  constant int := 6000;
  today      date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  select * into j from public.jorneys where id = p_jorney;
  if not found then raise exception 'jorney_not_found'; end if;

  select * into p from public.profiles where id = auth.uid() for update;
  if p.last_tick_at is not null and now() - p.last_tick_at < interval '1500 milliseconds' then
    raise exception 'too_fast';
  end if;
  if p.xp_today_date is distinct from today then p.xp_today := 0; end if;

  gain := least(j.xpps * 2, greatest(daily_cap - p.xp_today, 0));
  if gain <= 0 then raise exception 'daily_cap'; end if;
  old_level := p.level;

  update public.profiles set
    experience     = experience + gain,
    level          = public.level_for(experience + gain),
    xp_by_category = jsonb_set(xp_by_category, array[j.category],
                       to_jsonb(coalesce((xp_by_category ->> j.category)::int, 0) + gain)),
    last_tick_at   = now(),
    xp_today       = p.xp_today + gain,
    xp_today_date  = today
  where id = auth.uid()
  returning * into p;

  if p.level > old_level then
    insert into public.notifications (user_id, type, data)
    values (p.id, 'level', jsonb_build_object('level', p.level));
  end if;

  return json_build_object(
    'gain', gain, 'leveled_up', p.level > old_level, 'level', p.level,
    'experience', p.experience, 'xp_by_category', p.xp_by_category,
    'xp_today', p.xp_today, 'daily_cap', daily_cap);
end $$;

-- Limites contra spam
create or replace function private.rate_limit()
returns trigger language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if tg_table_name = 'posts' then
    select count(*) into n from public.posts
      where author_id = new.author_id and created_at > now() - interval '10 minutes';
    if n >= 5 then raise exception 'rate_limit'; end if;
  elsif tg_table_name = 'comments' then
    select count(*) into n from public.comments
      where author_id = new.author_id and created_at > now() - interval '10 minutes';
    if n >= 20 then raise exception 'rate_limit'; end if;
  end if;
  return new;
end $$;

drop trigger if exists posts_rate_limit on public.posts;
create trigger posts_rate_limit before insert on public.posts
  for each row execute function private.rate_limit();
drop trigger if exists comments_rate_limit on public.comments;
create trigger comments_rate_limit before insert on public.comments
  for each row execute function private.rate_limit();

-- Notificações de curtida e comentário
create or replace function private.notify_post_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare a uuid; r jsonb := to_jsonb(new);
begin
  select author_id into a from public.posts where id = new.post_id;
  if tg_table_name = 'likes' then
    if a is not null and a <> (r ->> 'user_id')::uuid then
      insert into public.notifications (user_id, actor_id, type, post_id)
      values (a, (r ->> 'user_id')::uuid, 'like', new.post_id);
    end if;
  else
    if a is not null and a <> (r ->> 'author_id')::uuid then
      insert into public.notifications (user_id, actor_id, type, post_id, data)
      values (a, (r ->> 'author_id')::uuid, 'comment', new.post_id,
              jsonb_build_object('text', left(r ->> 'text', 80)));
    end if;
  end if;
  return new;
end $$;

drop trigger if exists likes_notify on public.likes;
create trigger likes_notify after insert on public.likes
  for each row execute function private.notify_post_activity();
drop trigger if exists comments_notify on public.comments;
create trigger comments_notify after insert on public.comments
  for each row execute function private.notify_post_activity();

