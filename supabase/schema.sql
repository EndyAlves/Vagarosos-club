-- ---------------------------------------------------------------------
--  Nível a partir do XP total (mesma fórmula do front-end)
--  Para passar do nível L é preciso 600 + L² × 250 de XP total.
-- ---------------------------------------------------------------------
create or replace function public.level_for(xp int)
returns int language plpgsql immutable as $$
declare l int := 1;
begin
  while xp >= 600 + l * l * 250 loop l := l + 1; end loop;
  return l;
end $$;

