create table if not exists public.profiles (
  id             uuid primary key references auth.users (id) on delete cascade,
  username       text not null unique check (username ~ '^[a-z0-9._]{3,20}$'),
  full_name      text check (char_length(full_name) <= 60),
  position       text check (position in ('PG','SG','SF','PF','C')),
  height         text check (char_length(height) <= 6),
  birth          date check (birth between date '1930-01-01' and current_date),
  bio            text check (char_length(bio) <= 160),
  avatar_url     text check (avatar_url like '%/storage/v1/object/public/avatars/%'),
  onboarded      boolean not null default false,
  experience     int not null default 0,
  level          int not null default 1,
  xp_by_category jsonb not null default '{}'::jsonb,
  is_admin       boolean not null default false,
  last_tick_at   timestamptz,
  xp_today       int not null default 0,
  xp_today_date  date,
  created_at     timestamptz not null default now()
);
